// [2026-08-28 사장님 실측] 생성된 글을 외부 LLM(Fable)에 팩트체크시켰더니
// 할루시네이션이 다수 검출됐다. 기존 가드(contentFactCheckConstraint)는
// "자료에 없는 사실을 쓰지 마라"만 말한다. 그런데 실제로 새는 구멍은
// 자료에 있는 사실을 **잘못 조립**하는 쪽이었다:
//
//   - 두 지역의 사실이 한 문장에 섞임 ("A시와 B시는 1인당 25만원을 …")
//   - 자료엔 "약 70%"인데 본문은 "전국 모든 지자체가"로 승격
//   - '출생연도 끝자리'(요일제 기준)를 '생년월일 끝자리'로 바꿔 씀 — 다른 제도다
//   - "이달 말까지" — 발행 시점이 지나면 거짓이 되는 상대 날짜
//   - 자료엔 제도 이름만 있는데 본문이 도입 이유·전망을 지어냄
//
// 다섯 항목 모두 "자료에 있는 단어"로 만들어지기 때문에 기존 grounding 검사
// (numericGroundingCheck·sourceFidelityCheck)를 통과한다. 지시로 막아야 한다.
//
// 산문이 아니라 금지 목록으로 준다 — sourceFactChecklist에서 확인한 것과 같은
// 이유다. 모델은 산문 지시를 흘리고 목록은 지킨다.

/** 블록 주입 여부. 설정에서 끌 수 있게 하되 기본은 ON. */
export function isFactDisciplineGuardEnabled(
  config?: Record<string, unknown> | null,
): boolean {
  return (config as Record<string, unknown> | null)?.factDisciplineGuard !== false;
}

export function buildFactDisciplineGuardBlock(): string {
  return `## 팩트 규율 — 자료를 잘못 조립하는 일곱 가지 (위반 시 그 문장 삭제)

자료에 있는 단어만 써도 사실은 틀어진다. 아래 일곱은 전부 "자료에 있는 재료"로
만들어지는 오류이므로, 쓰기 전에 한 번씩 자문한다.

1. **주체를 섞지 않는다.** 한 문장에 둘 이상의 지역·기관·제품의 사실을 담지 않는다.
   지역별 금액·기간·조건이 다르면 지역마다 문장을 따로 쓴다.
   ⛔ "A시와 B시는 1인당 25만원을 지급한다" → ✅ "A시는 1인당 25만원이다. B시는 …"

2. **수량 한정어를 승격하지 않는다.** "모든·전부·유일·최초·최대·전국"은
   자료가 그 표현을 **그대로** 썼을 때만 쓴다.
   ⛔ 자료 "약 70%" → 본문 "대부분의" / "전국" (금지)  ✅ 본문도 "약 70%"

3. **고유명사는 자료 표기를 글자 그대로 옮긴다.** 제도명·공식 명칭·앨범명·공연장명·상품명 전부.
   비슷해 보여도 다른 것이다: '출생연도 끝자리' ≠ '생년월일 끝자리',
   '신청기간' ≠ '사용기간', 'K아레나 요코하마' ≠ '케이오 아레나'.
   ⛔ 긴 이름을 줄여 부르지 않는다 — 'THIS & THAT'을 '디'로 줄이면 다른 작품이 된다.
   자료에서 표기를 확인 못 했으면 그 이름을 문장에 쓰지 않는다.

4. **날짜는 월까지 붙여 쓴다.** 글은 발행 뒤에도 읽힌다.
   ⛔ 상대 날짜: "이달 말까지", "다음 주부터", "내일", "올해 안에"
   ⛔ **월 없는 날짜**: "23일 0시 공개", "29일과 30일 양일간", "19일 이후"
   ✅ "6월 23일 공개", "8월 29~30일", "9월 19~20일"
   자료에 월이 없으면 그 날짜를 쓰지 않는다. 날짜를 옳게 못 쓰면 안 쓰는 게 낫다.

5. **지난 일을 지금 일처럼 쓰지 않는다(시의성).** 수집 자료에는 몇 달 전 기사가 섞여 있다.
   - 각 사실이 **언제의 일인지** 먼저 확인한다. 시점을 모르면 그 사건을 쓰지 않는다.
   - 오래된 사건을 꼭 다뤄야 하면 **"지난 6월 23일"처럼 시점을 명시**한다.
     시점 없이 쓰면 독자는 방금 일어난 일로 읽는다.
   - 재료 앞의 **[YYYY-MM-DD 작성] 라벨은 그 글이 쓰인 날짜**다. 사건이 일어난 날짜가 아니다.
     라벨의 날짜를 본문에 사건 날짜처럼 옮기지 마라. 오늘 날짜도 본문에 쓰지 않는다.
     라벨은 기사 속 "오는 29일" 같은 상대 표현을 **몇 월인지 계산하는 데만** 쓴다.
   - 지금 다루는 사건과 **시점이 다른 기사는 문단을 합치지 않는다.** 다른 달의 행사·
     다른 공연의 숫자를 이번 소식 옆에 나란히 놓으면 같은 시기 일로 오독된다.

6. **확인 못 한 정보는 언급 자체를 하지 않는다.** 삭제가 원칙이다.
   ⛔ "…관련한 언급도 자료에 나오는데, 공식 공지에서 확인하세요"
   ⛔ "정확한 내용은 확인되지 않았습니다", "자료에는 없지만"
   검증 못 한 것을 지어내지 않는 건 옳다. 그러나 그 불확실성을 독자에게 중계하지는
   말고, 그냥 그 문장을 뺀다.

7. **이유·유래·전망을 지어내지 않는다.** 자료에 설명이 있을 때만 그 설명을 쓴다.
   없으면 "~로 불린다"·"~가 시행된다" 수준에서 멈춘다.
   ⛔ "소비 진작 효과를 노린 것으로 보인다", "내년에는 확대될 전망이다" (자료 없으면 금지)

⚠️ 자료에 구체적인 이름·날짜·회차가 **있는데도** 뭉뚱그리지 마라. "브라질 대형 공연"이
아니라 자료에 적힌 행사명 그대로, "19일 이후 일정"이 아니라 자료에 적힌 도시와 날짜 그대로.`;
}

/** 시스템 프롬프트 말미에 규율 블록을 덧붙인다. 원본 문자열은 변경하지 않는다. */
export function appendFactDisciplineGuard(
  systemPrompt: string,
  enabled: boolean,
): string {
  if (!enabled) return systemPrompt;
  return `${systemPrompt}\n\n${buildFactDisciplineGuardBlock()}`;
}
