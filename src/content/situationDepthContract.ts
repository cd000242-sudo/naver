/**
 * [2026-07-31] 상황별 깊이 계약 — "AI가 1초 만에 답하는 글"에서 벗어나기.
 *
 * 배경(사용자 제공 실전 자료 요약): 생성형 AI 사용률이 급증하면서
 * "여권 재발급 방법" 같은 단순 정보 나열형 글은 검색 결과에서 AI 요약에
 * 밀려 클릭 자체가 사라지고 있다. 살아남는 글의 공통점은 세 가지였다.
 *   1) AI가 만들 수 없는 디테일 — 언제/누구와/어떤 조건에서/얼마나 걸렸는지
 *   2) 검색자의 결정을 대신 좁혀줌 — 비교, 왜 추천/비추천, 누구에게 맞는지
 *   3) 좁고 깊은 주제 — "제주도 렌트카"가 아니라 "아이와 함께 제주도 렌트카"
 *
 * 중요한 전제: 직접 경험이 없어도 된다. 자료를 읽고 절차를 따라가 본 사람의
 * 시선(간접 경험)이면 충분하다. 다만 **없는 경험을 지어내는 것은 금지**다.
 * 그래서 이 계약은 근거 상태에 따라 요구하는 디테일의 종류를 바꾼다.
 */
export interface SituationDepthSource {
  /** 사용자가 입력한 직접 경험 메모 */
  personalExperience?: unknown;
  /** 크롤링·자료 원문 (간접 경험 서술의 근거) */
  rawText?: unknown;
}

function hasFirstPartyMemo(source?: SituationDepthSource | null): boolean {
  return String(source?.personalExperience ?? '').trim().length >= 8;
}

function hasGroundingText(source?: SituationDepthSource | null): boolean {
  return String(source?.rawText ?? '').trim().length >= 200;
}

export function buildSituationDepthContract(source?: SituationDepthSource | null): string {
  const firstParty = hasFirstPartyMemo(source);
  const grounded = hasGroundingText(source);

  const detailRule = firstParty
    ? `- [디테일 — 직접 경험 있음] 입력한 경험 메모의 육하원칙을 본문에 살려라.
  언제(요일·시간대까지), 누구와(인원·연령대), 어디서, 무엇을, 어떻게, 왜.
  그리고 결과가 어땠는지와 다음에 또 할지까지 쓴다.
  예: "주말 오후 2시에 갔더니 40분 기다렸다" / "8세·9세 데리고 갔다"
  → 이런 문장은 AI가 만들 수 없다. 이게 이 글이 검색 결과에서 살아남는 이유다.
  ⛔ 메모에 없는 시간·인원·금액·대기시간을 새로 만들지 마라.`
    : grounded
      ? `- [디테일 — 자료 기반 간접 경험] 직접 가보지 않았어도 자료를 끝까지 따라가 본
  사람의 시선으로 쓴다. 신청 절차라면 첫 화면부터 어떤 인증이 필요하고 어떤
  서류를 어디서 올리는지, 모바일로도 되는지, 어디서 막히기 쉬운지를 순서대로
  구체화한다. 자료에 있는 조건·예외·기한을 그냥 나열하지 말고 "이 경우엔 이렇게
  갈린다"로 연결한다.
  ⛔ 자료에 없는 대기시간·후기·개인 감상을 지어내지 마라. 대신 자료가 실제로
    말하는 절차와 조건을 남들보다 깊게 풀어라.`
      : `- [디테일 — 근거 부족] 확인된 자료가 적다. 일반론으로 분량을 채우지 말고,
  독자가 스스로 판단할 기준과 확인 순서를 구체적으로 준다.
  ⛔ 없는 수치·후기·경험을 만들어 채우지 마라. 짧고 정확한 편이 낫다.`;

  return `[SITUATION DEPTH — 검색자의 상황을 해결하는 글]
AI가 1초 만에 요약해 주는 단순 정보 나열은 더 이상 읽히지 않는다. 이 글은
"검색한 사람의 구체적인 상황"을 해결해야 한다.

${detailRule}

- [상황 분기] 같은 질문이라도 조건에 따라 답이 갈린다. 최소 2가지 상황을 나눠서
  각각의 답을 준다. (예: 처음 신청 vs 재신청 / 아이 동반 vs 성인만 /
  급한 경우 vs 여유 있는 경우 / 온라인 vs 방문)
  독자가 "내 경우는 어디에 해당하지?"를 스스로 찾을 수 있어야 한다.

- [결정 지원] 정보만 주고 끝내지 않는다. 선택지가 둘 이상이면 무엇이 어떻게
  다른지 구체적으로 비교하고, 어떤 사람에게 무엇이 맞는지 짚어준다.
  숫자만 나열하지 말고 그 숫자가 생활에서 뭘 뜻하는지 번역한다.
  (예: "6.9인치"가 아니라 "한 손으로 쥐면 위쪽 버튼에 손가락이 안 닿는다")

- [좁고 깊게] 주제를 넓게 훑지 말고 검색자가 실제로 처한 상황 하나를 깊게 판다.
  넓은 개괄 3문단보다 좁은 상황 1개의 구체적인 해결이 훨씬 오래 노출된다.

- [질문 선점] 이 글을 읽는 사람이 읽고 나서도 남을 질문 1~2개를 본문 안에서
  미리 답한다. "그럼 이 경우는요?"가 댓글로 올 만한 것을 먼저 처리한다.`;
}
