/**
 * [2026-07-31] 상황·경험 기반 제목 계약 — 제목 공식의 시대 종료.
 *
 * 사용자 지시: "예전 공식은 다 필요없다. 요즘은 상황이나 실제 경험이 들어간
 * 제목이 먹히는 시대다. 홈판 제목 / SEO 제목 / 쇼핑커넥트 전부."
 *
 * 배경: 숫자 리스트형("○○ 5가지"), 비밀 공개형("다들 모르는"), 총정리형처럼
 * 형태만 갈아끼우는 공식은 AI 요약이 이미 점령한 자리를 다시 노리는 것이라
 * 클릭으로 이어지지 않는다. 남는 제목은 두 종류다.
 *   A. 상황형 — 독자가 "지금 딱 내 얘기인데" 하고 멈추는 처지·조건·시점
 *   B. 경험형 — 실제로 겪어보고 알게 된 결과·판단 (근거가 있을 때만)
 *
 * 본문의 {@link buildSituationDepthContract}가 상황 깊이를 담당하고,
 * 이 계약은 그 상황을 제목까지 끌어올린다. 경험 표현은 근거 상태에 따라
 * 게이트가 걸리므로 없는 체험을 지어내는 방향으로는 열리지 않는다.
 */
export type SituationTitleMode = 'seo' | 'homefeed' | 'affiliate' | 'other';

export interface SituationTitleSource {
  /** 사용자가 입력한 직접 경험 메모 */
  personalExperience?: unknown;
  /** 크롤링·자료 원문 (간접 경험 서술의 근거) */
  rawText?: unknown;
}

function hasFirstPartyMemo(source?: SituationTitleSource | null): boolean {
  return String(source?.personalExperience ?? '').trim().length >= 8;
}

function hasGroundingText(source?: SituationTitleSource | null): boolean {
  return String(source?.rawText ?? '').trim().length >= 200;
}

/** 근거 상태별로 제목에 쓸 수 있는 경험 표현의 범위를 정한다. */
function buildExperienceGate(source?: SituationTitleSource | null): string {
  if (hasFirstPartyMemo(source)) {
    return `- [경험형 열림] 입력된 경험 메모가 있다. 실제로 겪어서 알게 된 것을 제목에 그대로 써라.
  겪은 뒤에야 알 수 있는 결과·판단이 제목에 들어갈 때 가장 강하다.
  예: "○○ 3개월 쓰고 나서야 알게 된 것" / "주말에 갔더니 이게 문제였다"
  ⛔ 단, 메모에 실제로 있는 사실만. 메모에 없는 기간·인원·금액·결과는 만들지 마라.`;
  }
  if (hasGroundingText(source)) {
    return `- [경험형 잠김 — 상황형으로 간다] 작성자 체험 메모가 없다. "써보니 / 직접 해보니 /
  다녀와보니 / 내돈내산" 같은 체험 후킹을 제목에 쓰면 계약 위반이다.
  대신 자료를 끝까지 따라가며 확인한 사람의 시선으로, 어디서 갈리고 어디서 막히는지를
  상황으로 제시해라.
  예: "○○ 신청, 이 조건이면 반려된다" / "○○, 모바일로만 하려면 걸리는 지점"`;
  }
  return `- [경험형 잠김 — 좁게 간다] 확인된 근거가 적다. 경험·수치·후기 표현을 제목에 쓰지 마라.
  독자가 처한 상황 조건 하나만 좁게 담고, 본문이 실제로 답할 수 있는 것만 약속해라.`;
}

/** 모드별 제약(SEO 키워드 앞 배치 등)과 상황 제목을 양립시킨다. */
function buildModeRule(mode: SituationTitleMode): string {
  if (mode === 'seo') {
    return `- [SEO 모드] 메인 키워드가 제목에 분명히 보여야 한다. 위치는 base R0-1을 따른다
  — 첫 3글자나 고정 위치로 옮기지 않는다. 자연스럽게 앞에 오는 것은 무방하다.
  상황 조각은 키워드 가까이 붙인다. 키워드를 뒤로 밀어내면서까지 상황을 앞세우지 마라.
  검색어를 제목에 원문 그대로 붙여 넣지 마라 — 핵심 명사는 유지하되,
  누구·방법·후기·뜻처럼 잘린 검색어투 꼬리는 자연스러운 문장으로 소화한다.
  정체·이유·뜻을 묻는 검색어는 물음표 질문형으로 소화해도 된다 —
  단 본문 도입 첫 문장이 그 질문에 바로 답해야 한다.
  예: 검색어 "여권 재발급 방법" → "여권 재발급, 주말에 급하게 해야 할 때 순서"
      "전세 계약, 집주인이 바뀐 상태로 들어갈 때 확인할 것"`;
  }
  if (mode === 'homefeed') {
    return `- [홈판 모드] 검색어를 맞출 필요가 없다. 키워드를 억지로 앞으로 끌어오지 마라.
  스크롤을 멈추게 하는 건 자극어가 아니라 "내 상황이랑 똑같은데?" 하는 순간이다.
  상황을 문장으로 자연스럽게 쓰고, 그 상황의 결말이나 판단을 뒤에 붙인다.
  예: "장 보러 갔다가 계산대에서 다시 뺀 것들"
      "부모님 병원 모시고 다니면서 알게 된 예약 순서"`;
  }
  if (mode === 'affiliate') {
    return `- [쇼핑 모드] 제품명 + "구매 직전에 갈리는 지점"으로 제목을 만든다.
  스펙 나열이나 "○○ 추천 TOP5"는 쓰지 않는다 — 그건 비교 사이트가 이미 가진 자리다.
  누가 사면 맞고 누가 사면 후회하는지, 어떤 조건에서 판단이 갈리는지를 제목에 담는다.
  예: "○○, 원룸이면 이 사이즈에서 갈린다" / "○○ 사기 전에 콘센트 위치부터 봐야 하는 이유"
  ⛔ 재고·마감·기간 한정("품절 임박", "오늘까지")과 결과 보장("무조건", "N주 만에")은 금지.`;
  }
  return `- [공통] 주제를 넓게 훑는 제목 대신, 독자 한 명이 처한 상황 하나를 제목에 담는다.`;
}

export function buildSituationTitleContract(
  mode: SituationTitleMode,
  source?: SituationTitleSource | null,
): string {
  return `[TITLE — 상황·경험 기준 (2026)]
제목 공식은 버린다. 숫자 리스트형("○○ 5가지"), 비밀 공개형("다들 모르는"),
총정리형("○○ 완벽 정리"), 충격·반전형은 전부 쓰지 않는다. 그 자리는 이미
AI 요약이 가져갔고, 독자는 그런 제목을 눈으로 걸러낸다.

지금 클릭되는 제목은 두 종류뿐이다.
  A. 상황형 — 읽는 사람이 "지금 딱 내 얘기인데" 하고 멈추는 구체적 처지·조건·시점
  B. 경험형 — 실제로 겪어보고 알게 된 결과·판단 (근거가 있을 때만)

- [상황 조각 — 필수] 제목에 아래 중 최소 1개가 들어가야 한다. 하나도 없으면 다시 써라.
  · 대상 조건: 처음인 사람 / 혼자 / 아이랑 / 부모님 모시고 / 예산이 정해진 / 세입자
  · 시점: 신청 전 / 계약 직전 / 3개월 쓰고 나서 / 이사 앞두고 / 성수기에
  · 환경: 주말 오후 / 지방에서 / 모바일로만 / 차 없이
  · 갈림길: 되는 경우와 안 되는 경우 / 바뀐 조건 / 사람마다 답이 갈리는 지점

${buildExperienceGate(source)}

${buildModeRule(mode)}

- [약속과 이행] 제목이 던진 질문·조건·결과에는 도입부 첫 3~5문장이 직접 답한다.
  "확인해보겠습니다", "알아보는 순서" 같은 진행 문구로 답을 미루면 독자는 바로 나간다.
  근거 자료가 그 답을 갖고 있지 않으면, 답할 수 있는 다른 상황으로 제목을 바꿔라.

- [금지] 상황이 없는 제목은 쓰지 않는다.
  "○○ 총정리", "○○ 방법", "○○ 완벽 가이드", "○○ 알아보기", "○○란?", "○○ 정리"
  → 전부 AI 요약이 이미 답한 자리다. 상황을 넣어 다시 써라.
  "이거 저만 그런가요?" 같은 빈 질문, 충격·경악·소름·대박 같은 자극어도 금지.`;
}
