// 제목이 자료에 있는 발언을 **요약해 버리는** 것을 막는다.
//
// [2026-09-17 생성 실측] 원문에 "식당 오픈 전부터 대기하고 있었다" 라는 문장이 그대로
// 있는데, 생성된 제목은 그것을 '식당 오픈 전 대기 목격담' 으로 요약했다. 뜻은 같지만
// 따옴표가 사라지면서 인용 장치를 통째로 잃었다.
//
// 실측(홈판 1,299편 vs 같은 블로그의 미진입 794편):
//   제목에 따옴표      홈판 56% : 미진입 43%  → 1.28배
//   조사+물음표 종결   홈판 1.1% : 미진입 2.5% → 0.43배
//
// 두 번째 숫자가 중요하다. "…제작진 답은?" 같은 마무리는 그 자체로는 대조군이 더 많이
// 쓰는 흔한 낚시 어미다. 그런데 이 형태로 홈판에 들어간 14편을 전부 열어 보면 **예외 없이
// 앞에 따옴표 인용이 박혀 있었다.**
//   3위  "후배들 믿는다" 8년 함께한 강호동 하차, 새 멤버 합류가 바꿀 분위기는?
//   5위  "월드컵 탈락 위기 홍명보" 모든 책임 인정... 연봉 20억 감독의 의전차는?
// 즉 끝의 '~는?' 은 혼자 일하는 장치가 아니라, 앞의 인용이 끌고 온 궁금증을 닫는 역할이다.
// 앞이 비어 있으면 낚시 어미만 남는다.

/** 제목이 실제 인용을 담았는가. 따옴표 짝이 맞고 안에 내용이 있어야 한다. */
export function titleCarriesQuote(title: string): boolean {
  const t = String(title || '');
  return /["“”].{2,}["“”]/.test(t) || /[‘'].{2,}[’']/.test(t);
}

/** 조사로 끊거나 조사+물음표로 닫는 마무리. */
function endsWithParticleHook(title: string): boolean {
  return /[은는이가을를의]\s*\??$/.test(String(title || '').trim());
}

export interface TitleQuoteUseInput {
  readonly title: string;
}

/**
 * 인용 사용에 대한 결함을 돌려준다. 빈 배열이면 통과.
 *
 * 하한 미달은 거절이 아니라 제목 재작성 트리거다 — 사람이 보고 고르는 것이 아니라
 * 파이프라인이 알아서 다시 쓰게 하는 것이 목적이다.
 */
export function computeHomefeedTitleQuoteIssues(input: TitleQuoteUseInput): string[] {
  const title = String(input.title || '').trim();
  if (!title) return [];
  if (titleCarriesQuote(title)) return [];

  const issues: string[] = [];

  /*
   * [근거 강도 — 약함] 홈판 9/1,283(0.70%) vs 미진입 14/793(1.77%), 발생비 0.40배.
   * Fisher 양측 p = 0.030 으로 0.05 는 넘지만 표본이 9 대 14 고, 같은 날 여러 패턴을
   * 함께 비교했으므로 다중비교를 감안하면 경계선이다.
   * (참고: '장치 0개' 규칙은 같은 검정에서 p = 2e-12 다 — 근거 강도가 다르다.)
   *
   * 그럼에도 거는 이유는 비용이 사실상 없기 때문이다 — 홈판 제목의 0.7% 만 재작성으로
   * 돌아간다. 뒤집을 실측이 나오면 이 블록만 지우면 된다.
   */
  if (endsWithParticleHook(title)) {
    issues.push(
      '조사·물음표로 끊었는데 앞에 인용이 없음'
      + ' — 발생비 0.40배(근거 약함). 홈판에 든 같은 형태는 앞에 인용이 있었다',
    );
  }

  /*
   * [기각된 규칙] "자료에 인용이 있는데 제목이 안 썼으면 재작성" 도 검토했다.
   * 실측 2,076편으로 재 보니 홈판 통과 83% : 미진입 통과 80% = 1.04배로 변별력이 없었고,
   * "건강식인 줄 알고 날마다 먹었는데.. 알고 보니 콜레스테롤 폭탄이었습니다" 같은
   * 반전형 승자까지 되돌렸다. 홈판 제목의 44% 는 따옴표 없이 들어간다 — 인용은
   * 강한 장치지 필수 장치가 아니다. 근거 없는 재작성은 비용만 남으므로 넣지 않는다.
   */

  return issues;
}
