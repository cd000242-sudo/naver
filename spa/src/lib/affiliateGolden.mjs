export const AFFILIATE_CATEGORIES = ['식품', '건강식품', '뷰티', '패션', '생활용품', '주방용품', '가전디지털', '가구/인테리어', '출산/육아', '반려동물', '스포츠/레저', '자동차용품', '기타'];

export function affiliateCategory(item = {}) {
  const fromNaver = NAVER_SHOPPING[Number(item.shoppingCategory)];
  if (fromNaver) return fromNaver;
  const fromCoupang = COUPANG[String(item.source || '').trim()];
  if (fromCoupang) return fromCoupang;
  const name = String(item.name || '');
  for (const [category, pattern] of [...PRE_RULES, ...NAME_RULES]) if (pattern.test(name)) return category;
  return '기타';
}

/** 카테고리별 개수와 그 안의 1위(compareGolden 기준) — 개수 많은 순, '기타'는 맨 뒤. */
export function summarizeCategories(entries) {
  const groups = new Map();
  for (const entry of entries) {
    const list = groups.get(entry.category) || [];
    groups.set(entry.category, [...list, entry.golden]);
  }
  return [...groups.entries()]
    .map(([category, goldens]) => ({ category, count: goldens.length, top: [...goldens].sort(compareGolden)[0] || null }))
    .sort((a, b) => Number(a.category === '기타') - Number(b.category === '기타') || b.count - a.count);
}
